/**
 * The Umayyad Mosque (Damascus) prayer timetable, taken from its Mawaqit page
 * (https://mawaqit.net/ar/m/ljm-lmwy-dmshq-dmshq-00000-syria, mosque #33637, Asia/Damascus). Fixed calendar by
 * month-day (the same every year), local Damascus time.
 *
 * [DATA] is the offline default shipped in the app. It was taken from the page as published and then run through
 * [TimetableCheck]: the mosque's own table had 6 typos, which were repaired (see tools/ and the unit tests).
 * At run time [MawaqitSync] downloads the page every 10 days and uses the newer, checked copy when there is one.
 * Line format: "month-day fajr shuruq dhuhr asr maghrib isha".
 */
object MosqueCalendar {
    /** The timetable shipped inside the app (already repaired). */
    val bundled: Map<String, DayTimes> by lazy {
        DATA.lineSequence().filter { it.isNotBlank() }.associate { line ->
            val p = line.trim().split(' ')
            p[0] to DayTimes(IntArray(6) { i -> p[1 + i].substring(0, 2).toInt() * 60 + p[1 + i].substring(3).toInt() })
        }
    }

    /** The timetable in use: set by [MawaqitSync] once the app has a downloaded copy, else the bundled one. */
    @Volatile var source: () -> Map<String, DayTimes> = { bundled }

    /** [fajr, dhuhr, asr, maghrib, isha] for [date], or null if the date is not in the table. */
    fun timesFor(date: LocalDate): List<LocalTime>? =
        source()["${date.monthValue}-${date.dayOfMonth}"]?.let { d -> listOf(0, 2, 3, 4, 5).map { d.time(it) } }

    /** Sunrise from the mosque's own timetable. */
    fun shuruqFor(date: LocalDate): LocalTime? = source()["${date.monthValue}-${date.dayOfMonth}"]?.time(1)

